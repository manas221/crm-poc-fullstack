import type { SVGProps } from 'react';

// Inline icons (no icon package). They inherit color via currentColor; size them with
// className, e.g. "size-4". Decorative by default: aria-hidden.

type IconProps = SVGProps<SVGSVGElement>;

function Icon({ className = 'size-4', children, ...props }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
      {...props}
    >
      {children}
    </svg>
  );
}

